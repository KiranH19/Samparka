import { createClient, SupabaseClient } from '@supabase/supabase-js';
import { Job, Business, Profile, Application, SavedJob, JobReport, AdminAuditLog } from '../types/database';

const rawUrl = import.meta.env.VITE_SUPABASE_URL as string | undefined;
const rawAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY as string | undefined;

// Check if credentials are authentic (not placeholders or empty)
export const isSupabaseConfigured = (): boolean => {
  if (typeof process !== 'undefined' && (process.env?.NODE_ENV === 'test' || process.env?.VITEST === 'true')) return false;
  if (!rawUrl || !rawAnonKey) return false;
  if (rawUrl.includes('your-project') || rawAnonKey.includes('your-anon')) return false;
  try {
    const url = new URL(rawUrl);
    return url.protocol === 'http:' || url.protocol === 'https:';
  } catch {
    return false;
  }
};

export const getSupabaseConfig = () => ({
  url: rawUrl || '',
  isConfigured: isSupabaseConfigured(),
});

// Real Supabase client initialized when URL & Key are valid
export const supabase: SupabaseClient = isSupabaseConfigured()
  ? createClient(rawUrl!, rawAnonKey!, {
      auth: {
        persistSession: true,
        autoRefreshToken: true,
        detectSessionInUrl: true,
      },
    })
  : (createClient('https://placeholder-samparka.supabase.co', 'placeholder-anon-key', {
      auth: {
        persistSession: false,
        autoRefreshToken: false,
      },
    }));

